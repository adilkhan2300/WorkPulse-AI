"""
Reports and Exports View for WorkPulse AI
Generates publication-quality PDF executive management reports,
consolidated multi-tab Excel workbooks, and modular CSV datasets.
"""

import streamlit as st
import pandas as pd
from datetime import datetime
from typing import Dict, Any

from modules.productivity_metrics import calculate_executive_kpis, calculate_department_breakdown
from modules.bottleneck_detection import detect_operational_bottlenecks
from modules.capacity_planning import calculate_capacity_utilization
from modules.intervention_engine import generate_evidence_based_interventions
from modules.cost_analysis import compute_operational_cost_breakdown
from modules.statistical_analysis import prepare_productivity_analytical_dataset, run_diminishing_returns_regression
from modules.llm_insights import generate_management_llm_insight
from modules.reporting import generate_pdf_management_report, generate_multi_tab_excel

def render_reports_view(datasets: Dict[str, pd.DataFrame]):
    st.markdown("## 📑 Reports & Analytical Exports")
    st.caption("Generate executive PDF management briefs, download consolidated Excel workbooks, or export granular CSV data slices.")

    kpis = calculate_executive_kpis(datasets)
    dept_df = calculate_department_breakdown(datasets)
    bottlenecks = detect_operational_bottlenecks(datasets)
    capacity_df = calculate_capacity_utilization(datasets)
    interventions = generate_evidence_based_interventions(datasets, kpis, bottlenecks, capacity_df)
    costs = compute_operational_cost_breakdown(datasets, kpis)
    analysis_df = prepare_productivity_analytical_dataset(datasets)
    reg_res = run_diminishing_returns_regression(analysis_df)
    
    # Retrieve or generate executive insight for report
    insight = st.session_state.get(
        "cached_llm_insight",
        generate_management_llm_insight(kpis, bottlenecks, reg_res)
    )

    # Section 1: Executive PDF Report
    st.markdown("### 📄 Executive PDF Management Brief (ReportLab)")
    st.markdown("""
    Generate an executive-ready PDF report formatted for leadership and MBA presentations. 
    Includes: Executive Diagnosis, Primary KPI Scorecards, Detected Operational Bottlenecks, Financial Inefficiency Burden, and 5-Pillar Strategic Interventions.
    """)

    with st.spinner("Compiling PDF Executive Report..."):
        try:
            pdf_bytes = generate_pdf_management_report(
                kpis=kpis,
                bottlenecks=bottlenecks,
                interventions=interventions,
                costs=costs,
                executive_insight=insight
            )
            report_name = f"WorkPulse_Executive_Report_{datetime.now().strftime('%Y%m%d')}.pdf"
            
            st.download_button(
                label="📥 Download Executive PDF Report",
                data=pdf_bytes,
                file_name=report_name,
                mime="application/pdf",
                type="primary",
                use_container_width=True
            )
        except Exception as e:
            st.error(f"Error generating PDF report: {e}")

    st.markdown("---")

    # Section 2: Multi-Tab Excel Export
    st.markdown("### 📊 Consolidated Multi-Tab Excel Workbook")
    st.markdown("Exports all 7 relational tables into a single formatted `.xlsx` workbook for external audits and financial modeling.")

    excel_bytes = generate_multi_tab_excel(datasets)
    st.download_button(
        label="📥 Download Consolidated Excel Workbook (.xlsx)",
        data=excel_bytes,
        file_name=f"WorkPulse_Consolidated_Data_{datetime.now().strftime('%Y%m%d')}.xlsx",
        mime="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        use_container_width=True
    )

    st.markdown("---")

    # Section 3: Granular Analytical CSV Exports
    st.markdown("### 📂 Modular Analytical CSV Exports")
    st.caption("Download targeted operational slices generated by WorkPulse calculation engines.")

    exp_col1, exp_col2, exp_col3 = st.columns(3)

    with exp_col1:
        if not dept_df.empty:
            st.download_button(
                label="📥 Department Summary (CSV)",
                data=dept_df.to_csv(index=False),
                file_name="workpulse_department_summary.csv",
                mime="text/csv",
                use_container_width=True
            )
        if bottlenecks:
            df_bns = pd.DataFrame(bottlenecks)
            st.download_button(
                label="📥 Operational Bottlenecks (CSV)",
                data=df_bns.to_csv(index=False),
                file_name="workpulse_detected_bottlenecks.csv",
                mime="text/csv",
                use_container_width=True
            )

    with exp_col2:
        if not capacity_df.empty:
            st.download_button(
                label="📥 Capacity Utilization (CSV)",
                data=capacity_df.to_csv(index=False),
                file_name="workpulse_capacity_utilization.csv",
                mime="text/csv",
                use_container_width=True
            )
        if interventions:
            df_itv = pd.DataFrame(interventions)
            st.download_button(
                label="📥 Strategic Interventions (CSV)",
                data=df_itv.to_csv(index=False),
                file_name="workpulse_strategic_interventions.csv",
                mime="text/csv",
                use_container_width=True
            )

    with exp_col3:
        if costs:
            df_cost = pd.DataFrame([costs])
            st.download_button(
                label="📥 Financial Cost Burden (CSV)",
                data=df_cost.to_csv(index=False),
                file_name="workpulse_financial_impact.csv",
                mime="text/csv",
                use_container_width=True
            )
        if not analysis_df.empty:
            st.download_button(
                label="📥 Merged Observation Dataset (CSV)",
                data=analysis_df.to_csv(index=False),
                file_name="workpulse_analytical_dataset.csv",
                mime="text/csv",
                use_container_width=True
            )
